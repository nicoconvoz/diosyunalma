// EL PRIMO PARTIDO - the captain's idea: give primes fractional divisors, split
// them into parts so they can somehow be multiples of something.
//
// The idea is not only realizable: it is three established branches of
// mathematics, and all three can be measured here.
//
//   A. CHANGE THE RING. In Z a prime is irreducible by definition. In Z[i] the
//      prime 5 is NOT prime: 5 = (2+i)(2-i). It IS a multiple. Exactly the
//      primes p = 1 (mod 4) split this way (Fermat 1640, Gauss 1832).
//   B. CHANGE THE COUNTING. The divisor function can be given a fractional
//      parameter: d_z is multiplicative with d_z(p) = z, generated by
//      zeta(s)^z. Setting z = 1/2 literally gives every prime HALF a divisor.
//   C. CHANGE THE PRIMES THEMSELVES. Beurling (1937) allows "primes" at any
//      real positions > 1 - at 2.5, at pi - and builds the whole analytic
//      theory on them.
//
// Verdicts fixed BEFORE running:
//   V1 (trap #16, declared) inside Z the statement "a prime has exactly two
//      divisors" is the DEFINITION. A fractional divisor in Z is a
//      contradiction in terms, not a discovery. Every route below works by
//      changing the ring, the counting function, or the primes - never by
//      finding a hidden divisor in Z.
//   V2 (route A) p splits in Z[i] if and only if p = 1 (mod 4), with an
//      explicit a^2 + b^2 = p. Violations must be ZERO, and the fraction that
//      splits must approach 1/2.
//   V3 (route B) with d_z(p) = z, the sum of d_z(n) up to x must track
//      x (log x)^(z-1) / Gamma(z) (Selberg-Delange). Measured for z = 1/2,
//      z = 1 (which must return the plain divisor count) and z = 2.
//   V4 (route C) a Beurling system with generalized primes at NON-INTEGER
//      positions must still produce a smooth counting law for its generalized
//      integers. Measured against the real integers as control.
// None of this is new: Fermat 1640, Gauss 1832, Selberg-Delange, Beurling 1937.
// Nothing here proves RH.

