func criba(n int) ([]bool, []int) {
	es := make([]bool, n+1)
	for i := 2; i <= n; i++ {
		es[i] = true
	}
	for p := 2; p*p <= n; p++ {
		if !es[p] {
			continue
		}
		for m := p * p; m <= n; m += p {
			es[m] = false
		}
	}
	var ps []int
	for i := 2; i <= n; i++ {
		if es[i] {
			ps = append(ps, i)
		}
	}
	return es, ps
}

// dosCuadrados finds a,b with a*a+b*b = p, or reports failure.
func dosCuadrados(p int) (int, int, bool) {
	for a := 1; a*a <= p; a++ {
		r := p - a*a
		b := int(math.Round(math.Sqrt(float64(r))))
		if b >= a && b*b == r {
			return a, b, true
		}
	}
	return 0, 0, false
}

// gamma via Lanczos, enough for the few values used here.
func gammaF(x float64) float64 {
	g := []float64{676.5203681218851, -1259.1392167224028, 771.32342877765313,
		-176.61502916214059, 12.507343278686905, -0.13857109526572012,
		9.9843695780195716e-6, 1.5056327351493116e-7}
	if x < 0.5 {
		return math.Pi / (math.Sin(math.Pi*x) * gammaF(1-x))
	}
	x -= 1
	a := 0.99999999999980993
	t := x + 7.5
	for i, c := range g {
		a += c / (x + float64(i) + 1)
	}
	return math.Sqrt(2*math.Pi) * math.Pow(t, x+0.5) * math.Exp(-t) * a
}

// sumaDz computes sum_{n<=N} d_z(n) using the smallest-prime-factor sieve.
func sumaDz(N int, z float64) []float64 {
	spf := make([]int32, N+1)
	for i := 2; i <= N; i++ {
		if spf[i] != 0 {
			continue
		}
		for m := i; m <= N; m += i {
			if spf[m] == 0 {
				spf[m] = int32(i)
			}
		}
	}
	d := make([]float64, N+1)
	d[1] = 1
	// coefficient of p^{-a} in (1-p^{-s})^{-z}: C(z+a-1, a)
	coef := func(a int) float64 {
		c := 1.0
		for i := 0; i < a; i++ {
			c *= (z + float64(i)) / float64(i+1)
		}
		return c
	}
	cache := map[int]float64{}
	for n := 2; n <= N; n++ {
		p := int(spf[n])
		m, a := n, 0
		for m%p == 0 {
			m /= p
			a++
		}
		c, ok := cache[a]
		if !ok {
			c = coef(a)
			cache[a] = c
		}
		d[n] = d[m] * c
	}
	out := make([]float64, N+1)
	s := 0.0
	for n := 1; n <= N; n++ {
		s += d[n]
		out[n] = s
	}
	return out
}

// beurling enumerates generalized integers (products of the given generalized
// primes, repetitions allowed) up to x, returning them sorted.
func beurling(gs []float64, x float64) []float64 {
	var out []float64
	var rec func(i int, v float64)
	rec = func(i int, v float64) {
		if i == len(gs) {
			out = append(out, v)
			return
		}
		for w := v; w <= x; w *= gs[i] {
			rec(i+1, w)
			if gs[i] < 1.0000001 {
				break
			}
		}
	}
	rec(0, 1)
	sort.Float64s(out)
	return out
}

